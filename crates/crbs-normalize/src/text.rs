//! 路径键控文本 handler：R DESCRIPTION 的 Built 墙钟行、javadoc 生成 HTML
//! 的内嵌生成时间。触发条件由 Format::detect 的路径+内容门禁决定，此处只
//! 做严格解析：结构不符整体放弃（原样保留），认得就归一到锚 UTC 定长串。

use crate::dos::{anchor_stamp, find_utc_stamps, UTC_STAMP_LEN};

/// DESCRIPTION 的 Built 字段行前缀（R CMD INSTALL 写入，值恒以 R 版本开头）。
const BUILT_PREFIX: &[u8] = b"Built: R ";
/// javadoc 生成注释标记：JDK 8 为 `(1.8.0_462)`、JDK 9+ 为 `(11.0.x)`，版本
/// 号不参与匹配，锚点只认标记本体。
const JAVADOC_MARKER: &[u8] = b"Generated by javadoc (";
/// 注释尾部 ` on <墙钟> -->` 的搜索窗口：真实注释从标记到 `-->` 约 70 字
/// 节，512 为 7 倍裕度；窗口外视为无注释尾，整体放弃。
const JAVADOC_TAIL_WINDOW: usize = 512;

/// R 包 DESCRIPTION 的 Built 行：23B UTC 戳就地替换为锚串（定长、文件
/// 尺寸不变，故收切片即可）。只认行首 Built 字段行；行内无合法戳即放弃；
/// 同文件其他日期字段（Date/Publication、Packaged 等源元数据）不触碰。
pub(crate) fn normalize_r_description(data: &mut [u8], epoch: i64) -> Result<bool, String> {
    let anchor = anchor_stamp(epoch)?;
    let mut changed = false;
    let mut line_start = 0;
    loop {
        let line_end = data[line_start..]
            .iter()
            .position(|&b| b == b'\n')
            .map_or(data.len(), |p| line_start + p);
        if data[line_start..].starts_with(BUILT_PREFIX) {
            // 字段值区起扫（避开前缀），行内首个合法戳即安装墙钟段
            let hit = find_utc_stamps(&data[line_start + BUILT_PREFIX.len()..line_end])
                .into_iter()
                .next()
                .ok_or_else(|| "Built line lacks a UTC stamp".to_string())?;
            let at = line_start + BUILT_PREFIX.len() + hit;
            if data[at..at + UTC_STAMP_LEN] != anchor {
                data[at..at + UTC_STAMP_LEN].copy_from_slice(&anchor);
                changed = true;
            }
        }
        if line_end == data.len() {
            break;
        }
        line_start = line_end + 1;
    }
    Ok(changed)
}

/// javadoc 生成 HTML 的 detect 门禁：字节级验证首个生成标记的注释窗口。
/// 窗口（标记到 `-->`，受 JAVADOC_TAIL_WINDOW 约束）内全部字节 < 0x80，
/// 保证改写段纯 ASCII、替换安全；窗口外高字节（Latin-1 正文等）不构成放
/// 弃理由，无标记或窗口无 `-->` 不认领。门禁只覆盖首个标记窗口，后续
/// 标记不经本判定（改写阶段逐窗口处理）。
pub(crate) fn javadoc_gate(data: &[u8]) -> bool {
    let Some(mark) = find(data, 0, data.len(), JAVADOC_MARKER) else {
        return false;
    };
    let mark_end = mark + JAVADOC_MARKER.len();
    let window_end = (mark_end + JAVADOC_TAIL_WINDOW).min(data.len());
    let Some(close) = find(data, mark_end, window_end, b"-->") else {
        return false;
    };
    data[mark..close].iter().all(|&b| b < 0x80)
}

/// javadoc 生成 HTML：`Generated by javadoc (...) on <墙钟> -->` 的时
/// 间段替换为锚 UTC 串 + 空格（写入固定自有格式，双侧同值即确定；不模仿
/// javadoc 的 locale 墙钟形态，星期/时区缩写长度可变故按变长段处理，整文
/// 件重写）。已归一文件二次运行字节不变。
pub(crate) fn normalize_javadoc_html(data: &mut Vec<u8>, epoch: i64) -> Result<bool, String> {
    let anchor = anchor_stamp(epoch)?;
    // 收集编辑区间（原坐标）：每个标记消费自己的注释尾，区间天然不重叠
    let mut edits: Vec<(usize, usize)> = Vec::new();
    let mut from = 0;
    while let Some(mark) = find(data, from, data.len(), JAVADOC_MARKER) {
        let mark_end = mark + JAVADOC_MARKER.len();
        let window_end = (mark_end + JAVADOC_TAIL_WINDOW).min(data.len());
        let close = find(data, mark_end, window_end, b"-->")
            .ok_or_else(|| "javadoc comment has no --> terminator".to_string())?;
        let on = find(data, mark_end, close, b" on ")
            .ok_or_else(|| "javadoc comment has no ' on ' separator".to_string())?;
        edits.push((on + 4, close));
        from = close + 3;
    }
    // detect 门禁保证至少一个标记；防御空编辑集
    if edits.is_empty() {
        return Ok(false);
    }
    let mut changed = false;
    // 倒序应用使前方坐标不失效；写回形态统一为 "<锚串> -->"
    let replacement: Vec<u8> = anchor
        .iter()
        .copied()
        .chain(std::iter::once(b' '))
        .collect();
    for (start, end) in edits.iter().rev() {
        if data[*start..*end] != replacement[..] {
            changed = true;
        }
        data.splice(*start..*end, replacement.iter().copied());
    }
    Ok(changed)
}

/// 在 `hay[from..to)` 内定位首个 `needle`。
fn find(hay: &[u8], from: usize, to: usize, needle: &[u8]) -> Option<usize> {
    let window = hay.get(from..to)?;
    window
        .windows(needle.len())
        .position(|w| w == needle)
        .map(|p| p + from)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 锚样例：2026-10-08 11:29:12 UTC。
    const ANCHOR: i64 = 1_791_458_952;
    const ANCHOR_STAMP: &str = "2026-10-08 11:29:12 UTC";

    /// 真实形态 DESCRIPTION 尾部（压力测试批次发现的形态）：Built 行含墙钟戳，
    /// 前置 Date/Publication 源元数据行同格式日期。
    fn description_bytes(stamp: &str) -> Vec<u8> {
        let mut v = Vec::new();
        v.extend_from_slice(b"Package: jsonlite\nVersion: 1.7.3\nLicense: MIT\n");
        v.extend_from_slice(b"Date/Publication: 2022-01-17 08:42:42 UTC\n");
        v.extend_from_slice(
            format!("Built: R 4.0.5; x86_64-cuos-linux-gnu; {stamp} UTC; unix\n").as_bytes(),
        );
        v
    }

    /// DESCRIPTION：仅 Built 行戳换锚（定长、尺寸不变），Date/Publication
    /// 原样；再跑幂等。
    #[test]
    fn description_replaces_built_stamp_only() {
        let mut data = description_bytes("2026-10-11 07:11:17");
        let original_len = data.len();
        assert!(normalize_r_description(&mut data, ANCHOR).unwrap());
        assert_eq!(data.len(), original_len);
        let text = String::from_utf8(data.clone()).unwrap();
        assert!(text.contains(&format!(
            "Built: R 4.0.5; x86_64-cuos-linux-gnu; {ANCHOR_STAMP}; unix"
        )));
        assert!(text.contains("Date/Publication: 2022-01-17 08:42:42 UTC"));
        assert!(!text.contains("2026-10-11 07:11:17"));

        assert!(!normalize_r_description(&mut data, ANCHOR).unwrap());
        assert_eq!(String::from_utf8(data).unwrap(), text);
    }

    /// 非 R 的 DESCRIPTION（无 Built 行）不触碰；含 Built 行但戳段缺失/不
    /// 合法的整体放弃且原样保留。
    #[test]
    fn description_rejects_or_skips_unrecognized() {
        let mut plain = b"Package: foo\nDate/Publication: 2022-01-17 08:42:42 UTC\n".to_vec();
        let original = plain.clone();
        assert!(!normalize_r_description(&mut plain, ANCHOR).unwrap());
        assert_eq!(plain, original);

        let mut no_stamp = b"Built: R 4.0.5; x86_64-pc-linux-gnu; yesterday; unix\n".to_vec();
        let original = no_stamp.clone();
        assert!(normalize_r_description(&mut no_stamp, ANCHOR).is_err());
        assert_eq!(no_stamp, original);

        let mut garbage =
            b"Built: R 4.0.5; x86_64-pc-linux-gnu; 2026-99-99 07:11:17 UTC; unix\n".to_vec();
        let original = garbage.clone();
        assert!(normalize_r_description(&mut garbage, ANCHOR).is_err());
        assert_eq!(garbage, original);
    }

    /// 真实 javadoc 注释（压力测试批次发现的形态，JDK 8 形态）换锚为自有 UTC
    /// 串；注释外日期不触碰；再跑幂等字节不变。
    #[test]
    fn javadoc_replaces_generation_stamp() {
        let mut data = b"<!DOCTYPE HTML>\n<!-- NewPage -->\n<html lang=\"en\">\n<head>\n<!-- Generated by javadoc (1.8.0_462) on Sun Oct 11 15:04:49 CST 2026 -->\n<meta http-equiv=\"Content-Type\">\n".to_vec();
        assert!(normalize_javadoc_html(&mut data, ANCHOR).unwrap());
        let text = String::from_utf8(data.clone()).unwrap();
        assert!(text.contains(&format!(
            "<!-- Generated by javadoc (1.8.0_462) on {ANCHOR_STAMP} -->"
        )));
        assert!(!text.contains("CST"));

        let once = data.clone();
        assert!(!normalize_javadoc_html(&mut data, ANCHOR).unwrap());
        assert_eq!(data, once);
    }

    /// 多标记文件全部归一；标记缺 `-->` 或缺 ` on ` 分隔整体放弃。
    #[test]
    fn javadoc_multi_marker_and_rejects_malformed() {
        let mut data = b"<!-- Generated by javadoc (1.8.0_462) on Sun Oct 11 15:04:49 CST 2026 -->\n<p>mid</p>\n<!-- Generated by javadoc (17.0.10) on Wed Sep  3 00:00:01 UTC 2025 -->\n".to_vec();
        assert!(normalize_javadoc_html(&mut data, ANCHOR).unwrap());
        let text = String::from_utf8(data).unwrap();
        assert_eq!(text.matches(ANCHOR_STAMP).count(), 2);

        let mut no_close =
            b"<!-- Generated by javadoc (1.8.0_462) on Sun Oct 11 15:04:49 CST 2026\n".to_vec();
        assert!(normalize_javadoc_html(&mut no_close, ANCHOR).is_err());

        let mut no_on = b"<!-- Generated by javadoc (1.8.0_462) -->\n".to_vec();
        assert!(normalize_javadoc_html(&mut no_on, ANCHOR).is_err());
    }

    /// find：窗界裁剪与未命中。
    #[test]
    fn find_bounds() {
        let hay = b"abcdef";
        assert_eq!(find(hay, 0, 6, b"cd"), Some(2));
        assert_eq!(find(hay, 3, 6, b"cd"), None);
        assert_eq!(find(hay, 0, 3, b"cd"), None);
        assert_eq!(find(hay, 6, 6, b"a"), None);
        assert_eq!(find(hay, 2, 4, b"abcdef"), None);
    }
}
